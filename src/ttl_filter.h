#ifndef TTL_FILTER_H
#define TTL_FILTER_H
#include <stdatomic.h>
#include <stdint.h>

/*! \file ttl_filter.h
 * Фильтр приёма. Контракт файла.
 *
 * Сервис публикует, хранит и выдаёт. Информационная безопасность —
 * каркас этих операций. Фильтр держит приём: собирает сигналы отказа
 * и на живой записи молчит. Срок здесь — время жизни записи.
 * Поле TTL заголовка IP к этому сроку не относится.
 *
 * Устойчивое развитие — сохранять идентичность и продолжать операции
 * при изменении среды, не разрушая собственных оснований.
 * Пока сигнала нет, пакет уходит и выдача продолжается.
 * Живая запись молчит и не кормит интерес ответом.
 * Стек держит 256 записей и с кучи не растёт.
 * Ширина, срок и счётчик останавливаются на 65535.
 * Таблица и слово записи остаются целыми при любом потоке.
 *
 * Один сигнал кладёт адрес или диапазон на стек. Это бан.
 * Серия по той же записи растит срок и поднимает её на вершину. Это бан-бан.
 * Сигнал, который видит запись, обновляет её и новую ячейку не берёт.
 * Стек — один CAS на голове: индекс и поколение в одном слове.
 * Затвора и спинлока нет. Приём не ждёт очереди писателей.
 * Повтор стоит у вершины, проход останавливается на первом совпадении.
 * Запись — одно атомарное слово uint64_t: адрес, ширина, срок.
 * Счётчик и звено стека лежат рядом с этим словом.
 * Срок и ширина записаны до переноса. Неудачный CAS в звенья ничего не пишет.
 * Пока цепочка снята, новый читатель видит пустую голову и уходит.
 * Старый читатель идёт по своим звеньям и останавливается на битом индексе или конце.
 */

enum { TTL_CAP = 256 };
enum { TTL_MISS = 0, TTL_HIT = 1, TTL_NEW = 2, TTL_FULL = 3 };
enum { TTL_PASS = 1, TTL_HOLD = 0 };

typedef union {
	struct {
		_Atomic uint64_t node[TTL_CAP];
		int16_t link[TTL_CAP];
		uint16_t hits[TTL_CAP]; /* hits — число сигналов по записи */
		_Atomic uint64_t head;
		_Atomic uint64_t free_top;
	};
	unsigned char bytes[4096];
} TtlFilter;

_Static_assert(sizeof(TtlFilter) == 4096, "ttl filter");

/* Пустой фильтр: свободный стек полон, голова пуста, слова записей нулевые. */
void ttl_filter_init(TtlFilter *f);

/* Сигнал отказа на отрезке [lo, hi]. Если lo > hi, границы меняются местами.
   Первая запись отрезка — TTL_NEW. Повтор того же отрезка, уже с насыщенной
   шириной, — TTL_HIT: срок = now + base + число сигналов × step, не выше
   65535, запись поднимается на вершину. Свободной ячейки нет — TTL_FULL,
   стек не меняется этой попыткой. Ширина выше 65535 хранится как 65535. */
int  ttl_signal(TtlFilter *f, uint32_t lo, uint32_t hi, int64_t now, int64_t base, int64_t step);

/* Пустая голова или битый индекс — сразу TTL_PASS, не ждать.
   TTL_HOLD — живая запись покрывает адрес и срок ещё не вышел, порт молчит.
   Чтение звенья не пишет. */
int  ttl_pass(const TtlFilter *f, uint32_t addr, int64_t now);

/* Снимает цепочку. Записи со сроком <= now возвращает в свободный стек.
   Остальные ставит по убыванию срока, самый длинный — на вершине.
   Если цепочку забрать не удалось, стек остаётся как был. */
void ttl_sort(TtlFilter *f, int64_t now);

/* Пишет в lo адреса живых записей от вершины, не больше cap. Возвращает число. */
int  ttl_order(const TtlFilter *f, uint32_t *lo, int cap);

/* Число живых записей, не больше TTL_CAP. */
int  ttl_active(const TtlFilter *f);

/* Разведка приёма. Маска у службы, не в фильтре.
   Один код — один бит. Повтор ставит тот же бит. */
enum { TTL_BIT_NEW = 1u << 0, TTL_BIT_HIT = 1u << 1, TTL_BIT_FULL = 1u << 2 };

static inline unsigned ttl_mark(_Atomic unsigned *flags, int code)
{
	unsigned bit = 0;
	if (code == TTL_NEW) bit = TTL_BIT_NEW;
	else if (code == TTL_HIT) bit = TTL_BIT_HIT;
	else if (code == TTL_FULL) bit = TTL_BIT_FULL;
	if (!bit) return 0;
	return (unsigned)atomic_fetch_or(flags, bit);
}
#endif
